#!/usr/bin/env node
// Prints an idempotent psql script that records already-applied Drizzle migrations in
// drizzle.__drizzle_migrations, using the exact format of the installed drizzle-orm (0.45.x):
//   hash = sha256(file contents), created_at = journal entry "when".
// The migrator decides only from created_at, so recording the journal makes `drizzle-kit migrate` a no-op.
// It never touches application tables; run it only after drizzle-reconcile.sh proved the live schema.
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export function readMigrations(folder) {
  const journal = JSON.parse(readFileSync(join(folder, "meta", "_journal.json"), "utf8"));
  return journal.entries.map((entry) => {
    const sql = readFileSync(join(folder, `${entry.tag}.sql`), "utf8").replace(/\r\n/gu, "\n");
    if (!Number.isSafeInteger(entry.when)) throw new Error(`Invalid journal timestamp for ${entry.tag}`);
    return { tag: entry.tag, when: entry.when, hash: createHash("sha256").update(sql).digest("hex"), sql };
  });
}

export function buildBaselineSql(folder) {
  const migrations = readMigrations(folder);
  if (migrations.length === 0) throw new Error("No migrations found");
  const values = migrations.map((m) => `    ('${m.hash}', ${m.when})`).join(",\n");
  const tables = [...new Set(migrations.flatMap((m) => [...m.sql.matchAll(/CREATE TABLE "(\w+)"/gu)].map((x) => x[1])))];
  const tableList = tables.map((name) => `'${name}'`).join(", ");
  return `-- Generated by drizzle-baseline.mjs. Idempotent; records history only, never changes application tables.
\\set ON_ERROR_STOP on
BEGIN;
CREATE SCHEMA IF NOT EXISTS drizzle;
CREATE TABLE IF NOT EXISTS drizzle.__drizzle_migrations (
  id SERIAL PRIMARY KEY,
  hash text NOT NULL,
  created_at bigint
);
DO $guard$
DECLARE
  missing text;
  foreign_rows integer;
BEGIN
  SELECT string_agg(t, ', ') INTO missing FROM unnest(ARRAY[${tableList}]) AS t
   WHERE to_regclass(format('public.%I', t)) IS NULL;
  IF missing IS NOT NULL THEN
    RAISE EXCEPTION 'refusing to record history: application tables missing: %', missing;
  END IF;
  SELECT count(*) INTO foreign_rows FROM drizzle.__drizzle_migrations m
   WHERE NOT EXISTS (SELECT 1 FROM (VALUES
${values}
  ) v(hash, created_at) WHERE v.hash = m.hash AND v.created_at = m.created_at);
  IF foreign_rows > 0 THEN
    RAISE EXCEPTION 'refusing to record history: % existing row(s) do not match the migration journal', foreign_rows;
  END IF;
END
$guard$;
INSERT INTO drizzle.__drizzle_migrations (hash, created_at)
SELECT v.hash, v.created_at FROM (VALUES
${values}
) v(hash, created_at)
WHERE NOT EXISTS (SELECT 1 FROM drizzle.__drizzle_migrations m WHERE m.hash = v.hash AND m.created_at = v.created_at)
ORDER BY v.created_at;
COMMIT;
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const folder = resolve(process.argv[2] ?? join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..", "drizzle"));
  process.stdout.write(buildBaselineSql(folder));
}
